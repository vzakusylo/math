"""aerodoppler — учебная доплеровская обработка звука пролёта самолёта.

По аудиозаписи прямолинейного пролёта восстанавливаем параметры движения источника.
Это математическое ядро идеи из видео (эффект Доплера в фоновом гуле самолёта),
без шага определения географического места.

Модули:
  geo      — скорость звука, локальные координаты, расстояния.
  synth    — синтез звука пролёта (Доплер, запаздывание звука, затухание, гармоники, шум).
  spectro  — спектрограмма с «отбеливанием», поиск доплеровской кривой (Витерби),
             уточнение частоты центроидом и подгонка моделью прямолинейного пролёта
             → основная частота f0, скорость, дистанция CPA, момент пролёта.
  physics  — формула Доплера для движущегося источника и замкнутое решение для
             равномерного прямолинейного пролёта с учётом времени распространения звука.
  adsb     — (опционально) чтение треков ADS-B из CSV; для сопоставления с данными
             о реальных рейсах, если такие данные есть под рукой.

Демонстрация: ../demo_doppler.py — синтез → восстановление → сверка с истиной + график.
"""

